"""Run one ticket with explicit terminal approvals.

``ALENIA_MODE`` selects the services (default ``simulation``). ``--flow``
selects the orchestration: ``pipeline`` (default) is the deterministic UC1
pipeline with a labelled source on every line; ``agent`` is the LangChain
tool-calling agent. In live mode the CLI needs ``--ticket`` and every
official setting, and it never falls back to the simulation.
"""

import argparse
import json
from pathlib import Path
from uuid import uuid4

from pydantic import ValidationError

from hackaton_alenia.agent import run_ticket
from hackaton_alenia.approvals import Approval, ApprovalDenied, AuditApprovalGate
from hackaton_alenia.evaluation import evaluate
from hackaton_alenia.integrations.factory import ConfigurationError, build_model, build_services
from hackaton_alenia.llm_s import pipeline_model, simulated_model
from hackaton_alenia.pipeline import StatusNames, run_pipeline
from hackaton_alenia.settings import CASE_PATH, CASES_DIR, EXPECTED_DIR, EXPECTED_PATH, load_settings
from hackaton_alenia.sql_guard import is_read_only, read_only_reason

_ACTION_INFO = {
    "sql": (
        "Run a read-only SQL query",
        "read-only",
        "This action only reads data; it will not modify any table.",
        "query",
    ),
    "comment": (
        "Publish a comment on the ticket",
        "ticket state change",
        "This action changes the ticket state; it does not modify data tables.",
        "comment text",
    ),
    "status": (
        "Update the ticket status",
        "ticket state change",
        "This action changes the ticket status; it does not modify data tables.",
        "status value",
    ),
}


def _action_info(request):
    """Never reassure the human about a statement the local check cannot clear."""
    if request.action == "sql" and not is_read_only(request.payload):
        return (
            "Run a SQL statement NOT recognised as read-only",
            "NOT VERIFIED AS READ-ONLY",
            f"WARNING: this statement was not recognised as a single read-only query "
            f"({read_only_reason(request.payload)}). It may modify data or storage. "
            f"The local check is a guard rail, not a security boundary: it can be wrong "
            f"in both directions, so verify the statement yourself before approving.",
            "statement",
        )
    return _ACTION_INFO[request.action]


ORIGIN_LABELS = {
    "agent": "AGENT (generated by the model)",
    "script": "SCRIPT (composed by deterministic code)",
}

# Local, unverified status names used only by the simulation.
SIMULATION_STATUSES = StatusNames(proposal="resolved", review="review_required")


def _approval_prompt(request, context, sequence):
    kind, scope, scope_note, thing = _action_info(request)
    return (
        f"\n--- Approval request #{sequence} ---\n"
        f"Use case: {context.get('use_case', 'unknown')} | "
        f"Priority: {context.get('priority', 'unknown')}\n"
        f"Ticket: {request.ticket_id}\n"
        f"Action kind: {kind} ({scope})\n"
        f"Generated by: {ORIGIN_LABELS.get(request.origin, request.origin)}\n"
        f"{scope_note}\n"
        f"\n"
        f"Payload: {request.payload}\n"
        f"Purpose: {request.purpose}\n"
        f"\n"
        f'If you type "approve", the run will execute the exact {thing} shown above.\n'
        f"If you type anything else or press Ctrl-D, the run stops here and NOTHING is executed.\n"
        f"\n"
        f"Type approve to execute this action: "
    )


def human_decision(request, gate):
    print(_approval_prompt(request, gate.context, gate.sequence))
    try:
        answer = input().strip()
    except (EOFError, KeyboardInterrupt):
        return None
    return Approval(request, answer == "approve")


def resolve_case_paths(case_arg: str | None) -> tuple[Path, Path]:
    if case_arg is None:
        return CASE_PATH, EXPECTED_PATH
    case_path = Path(case_arg)
    if not case_path.is_absolute():
        case_path = CASES_DIR / case_path
    if case_path.suffix != ".json":
        case_path = case_path.with_suffix(".json")
    expected_path = EXPECTED_DIR / f"{case_path.stem}.json"
    return case_path, expected_path


def print_event(event: dict) -> None:
    print(f"[{event['source'].upper()}] {event['step']}: {event['summary']}")


def _live_parts(settings):
    """Build every live part, or report every missing setting at once."""
    parts, problems = {}, []

    def statuses():
        missing = [name for name, value in (("ALENIA_STATUS_PROPOSAL", settings.status_proposal),
                                            ("ALENIA_STATUS_REVIEW", settings.status_review)) if value is None]
        if missing:
            raise ConfigurationError("Live statuses missing required settings: " + ", ".join(missing))
        return StatusNames(proposal=settings.status_proposal, review=settings.status_review)

    for name, build in (("services", lambda: build_services(settings)), ("model", lambda: build_model(settings)),
                        ("statuses", statuses)):
        try:
            parts[name] = build()
        except ConfigurationError as error:
            problems.append(str(error))
    return parts, problems


def main() -> int:
    parser = argparse.ArgumentParser(description="Run one ticket with explicit human approvals.")
    parser.add_argument("--case", help="Simulation fixture in evals/cases or an absolute path (default: uc1_missing_mapping_s).")
    parser.add_argument("--evaluate", action="store_true", help="Simulation only: compare the result with local expectations.")
    parser.add_argument("--flow", choices=("pipeline", "agent"), default="pipeline",
                        help="pipeline: deterministic UC1 steps with labelled sources (default); agent: tool-calling agent.")
    parser.add_argument("--ticket", type=int, help="Live only: OpenProject work package id.")
    args = parser.parse_args()

    try:
        settings = load_settings()
    except ValidationError as error:
        # Print only the validation messages, never the rejected input values.
        for problem in error.errors():
            print(f"Configuration error: {problem['msg'].removeprefix('Value error, ')}")
        return 2

    live = settings.alenia_mode == "live"
    if live:
        print("LIVE: official services and the Model Serving endpoint; approvals are human.")
        if args.ticket is None:
            print("Live mode needs --ticket <OpenProject work package id>.")
            return 2
        parts, problems = _live_parts(settings)
        if problems:
            for problem in problems:
                print(f"Configuration error: {problem}")
            return 2
        services, model, statuses, ticket_id = parts["services"], parts["model"], parts["statuses"], args.ticket
    else:
        print("SIMULATION: scripted model and in-memory services; approvals are human.")
        case_path, expected_path = resolve_case_paths(args.case)
        try:
            case = json.loads(case_path.read_text())
        except (FileNotFoundError, json.JSONDecodeError) as error:
            print(f"Cannot load case {case_path}: {error}")
            return 2
        services = build_services(settings, simulated_case=case)
        model = pipeline_model(case) if args.flow == "pipeline" else simulated_model(case)
        statuses, ticket_id = SIMULATION_STATUSES, case["ticket"]["id"]

    run_id = uuid4().hex
    gate = AuditApprovalGate(
        lambda request: human_decision(request, gate),
        run_id=run_id,
    )
    try:
        if args.flow == "pipeline":
            result = run_pipeline(ticket_id, services, model, gate, statuses=statuses, emit=print_event)
        else:
            result = run_ticket(ticket_id, services, model, gate)
            result["flow"] = "agent"
    except ApprovalDenied as error:
        print(str(error))
        print(json.dumps({"run_id": run_id, "audit": [entry.as_dict() for entry in gate.ledger]}, indent=2))
        return 1
    result["simulation"] = not live
    if args.evaluate and not live:
        try:
            expected = json.loads(expected_path.read_text())
        except (FileNotFoundError, json.JSONDecodeError) as error:
            print(f"Cannot load expected result {expected_path}: {error}")
            return 2
        result["evaluation"] = evaluate(result, expected)
    result["run_id"] = run_id
    result["audit"] = [entry.as_dict() for entry in gate.ledger]
    print(json.dumps(result, indent=2))
    return 0 if result.get("evaluation", {}).get("passed", True) else 1


if __name__ == "__main__":
    raise SystemExit(main())
